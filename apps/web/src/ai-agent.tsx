function inlineContent(text: string): React.ReactNode[] {
  const pieces: React.ReactNode[] = [];
  // Only document links generated by Eliza are navigable. Other Markdown stays plain text.
  const tokens = /(\[([^\]]+)\]\((\/ai\?document=[a-f0-9-]{36})\)|\*\*([^*]+)\*\*|__([^_]+)__|`([^`]+)`|\/ai\?document=[a-f0-9-]{36})/gi;
  let previous = 0;
  for (const match of text.matchAll(tokens)) {
    const offset = match.index ?? 0;
    if (offset > previous) pieces.push(text.slice(previous, offset));
    if (match[3]) pieces.push(<a href={match[3]} key={offset}>{match[2]}</a>);
    else if (match[4] || match[5]) pieces.push(<strong key={offset}>{match[4] || match[5]}</strong>);
    else if (match[6]) pieces.push(<code key={offset}>{match[6]}</code>);
    else pieces.push(<a href={match[0]} key={offset}>{t('Open scanned document')}</a>);
    previous = offset + match[0].length;
  }
  if (previous < text.length) pieces.push(text.slice(previous));
  return pieces;
}
function messageContent(text: string) {
  const lines = linkedDocument(text).split('\n');
  const blocks: React.ReactNode[] = [];
  let index = 0;
  while (index < lines.length) {
    if (/^\|.+\|$/.test(lines[index]) && /^\|[\s:|-]+\|$/.test(lines[index + 1] ?? '')) {
      const headers = lines[index].split('|').slice(1, -1).map((v) => v.trim());
      index += 2;
      const rows: string[][] = [];
      while (index < lines.length && /^\|.+\|$/.test(lines[index]))
        rows.push(lines[index++].split('|').slice(1, -1).map((v) => v.trim()));
      blocks.push(
        <div className="ai-table-scroll" key={blocks.length}>
          <table>
            <thead><tr>{headers.map((header, i) => <th key={i}>{inlineContent(header)}</th>)}</tr></thead>
            <tbody>{rows.map((row, i) => <tr key={i}>{row.map((cell, j) => <td key={j}>{inlineContent(cell)}</td>)}</tr>)}</tbody>
          </table>
        </div>,
      );
      continue;
    }
    if (!lines[index].trim()) { index++; continue; }
    const list = /^\s*([-*]|\d+\.)\s+(.+)$/.exec(lines[index]);
    if (list) {
      const ordered = /\d/.test(list[1]);
      const items: string[] = [];
      while (index < lines.length) {
        const match = /^\s*([-*]|\d+\.)\s+(.+)$/.exec(lines[index]);
        if (!match || /\d/.test(match[1]) !== ordered) break;
        items.push(match[2]);
        index++;
      }
      const children = items.map((item, i) => <li key={i}>{inlineContent(item)}</li>);
      blocks.push(ordered ? <ol key={blocks.length}>{children}</ol> : <ul key={blocks.length}>{children}</ul>);
      continue;
    }
    const heading = /^#{1,3}\s+(.+)$/.exec(lines[index]);
    if (heading) {
      blocks.push(<h3 key={blocks.length}>{inlineContent(heading[1])}</h3>);
      index++;
      continue;
    }
    blocks.push(<p key={blocks.length}>{inlineContent(lines[index++])}</p>);
  }
  return blocks;
}
async function sendStream(
  id: string,
  message: string,
  documentId: string,
  onDelta: (text: string) => void,
): Promise<Detail> {
  const response = await fetch('/api/ai/conversations/' + id + '/messages/stream', {
    method: 'POST',
    credentials: 'same-origin',
    headers: { 'Content-Type': 'application/json', 'X-Eliza-Request': '1' },
    body: JSON.stringify({ message, ...(documentId ? { documentId } : {}) }),
  });
  if (!response.ok || !response.body) {
    const body = await response.json().catch(() => null);
    throw new Error(body?.message || t('Eliza AI could not complete the request. Try again.'));
  }
  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let buffer = '';
  let result: Detail | undefined;
  const consume = (frame: string) => {
    const event = frame.split('\n').find((line) => line.startsWith('event:'))?.slice(6).trim();
    const data = frame.split('\n').filter((line) => line.startsWith('data:')).map((line) => line.slice(5).trimStart()).join('\n');
    if (!event || !data) return;
    const value = JSON.parse(data);
    if (event === 'delta' && typeof value.text === 'string') onDelta(value.text);
    if (event === 'done') result = value as Detail;
    if (event === 'error') throw new Error(value.message || t('Eliza AI could not complete the request. Try again.'));
  };
  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    buffer = buffer.replace(/\r\n/g, '\n');
    let boundary: number;
    while ((boundary = buffer.indexOf('\n\n')) >= 0) {
      consume(buffer.slice(0, boundary));
      buffer = buffer.slice(boundary + 2);
    }
  }
  if (buffer.trim()) consume(buffer);
  if (!result) throw new Error(t('Eliza AI did not finish its answer. Try again.'));
  return result;
}
