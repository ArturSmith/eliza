import { DocumentViewer, type DocumentRecord } from './scanned-documents';

type Conversation = { id: string; title: string; created_at: string; updated_at: string };
type Message = {
  id: string;
  role: 'user' | 'assistant';
  content: string;
  document_id: string | null;
  created_at: string;
};
type Detail = { conversation: Conversation; messages: Message[] };
type Document = { id: string; filename: string; documentType: string; status: 'draft' | 'saved' };
function linkedDocument(text: string) {
  return text.replaceAll('/documents?id=', '/ai?document=');
}
const accepted = ['image/jpeg', 'image/png', 'image/webp', 'application/pdf'];
const fileLimit = 8_000_000;
function inlineContent(text: string): React.ReactNode[] {
  const pieces: React.ReactNode[] = [];
  // Only document links generated by Eliza are navigable. Other Markdown stays plain text.
  const tokens = /(\[([^\]]+)\]\((\/ai\?document=[a-f0-9-]{36})\)|\*\*([^*]+)\*\*|__([^_]+)__|`([^`]+)`|\/ai\?document=[a-f0-9-]{36})/gi;
  let previous = 0;
  for (const match of text.matchAll(tokens)) {
    const offset = match.index ?? 0;
    if (offset > previous) pieces.push(text.slice(previous, offset));
    if (match[3]) pieces.push(<a href={match[3]} key={offset}>{match[2]}</a>);
    else if (match[4] || match[5]) pieces.push(<strong key={offset}>{match[4] || match[5]}</strong>);
    else if (match[6]) pieces.push(<code key={offset}>{match[6]}</code>);
    else pieces.push(<a href={match[0]} key={offset}>{t('Open scanned document')}</a>);
    previous = offset + match[0].length;
  }
  if (previous < text.length) pieces.push(text.slice(previous));
  return pieces;
}
function messageContent(text: string) {
  const lines = linkedDocument(text).split('\n');
  const blocks: React.ReactNode[] = [];
  let index = 0;
  while (index < lines.length) {
    if (/^\|.+\|$/.test(lines[index]) && /^\|[\s:|-]+\|$/.test(lines[index + 1] ?? '')) {
      const headers = lines[index].split('|').slice(1, -1).map((v) => v.trim());
      index += 2;
      const rows: string[][] = [];
      while (index < lines.length && /^\|.+\|$/.test(lines[index]))
        rows.push(lines[index++].split('|').slice(1, -1).map((v) => v.trim()));
      blocks.push(
        <div className="ai-table-scroll" key={blocks.length}>
          <table>
            <thead><tr>{headers.map((header, i) => <th key={i}>{inlineContent(header)}</th>)}</tr></thead>
            <tbody>{rows.map((row, i) => <tr key={i}>{row.map((cell, j) => <td key={j}>{inlineContent(cell)}</td>)}</tr>)}</tbody>
          </table>
        </div>,
      );
      continue;
    }
    if (!lines[index].trim()) { index++; continue; }
    const list = /^\s*([-*]|\d+\.)\s+(.+)$/.exec(lines[index]);
    if (list) {
      const ordered = /\d/.test(list[1]);
      const items: string[] = [];
      while (index < lines.length) {
        const match = /^\s*([-*]|\d+\.)\s+(.+)$/.exec(lines[index]);
        if (!match || /\d/.test(match[1]) !== ordered) break;
        items.push(match[2]);
        index++;
      }
      const children = items.map((item, i) => <li key={i}>{inlineContent(item)}</li>);
      blocks.push(ordered ? <ol key={blocks.length}>{children}</ol> : <ul key={blocks.length}>{children}</ul>);
      continue;
    }
    const heading = /^#{1,3}\s+(.+)$/.exec(lines[index]);
    if (heading) {
      blocks.push(<h3 key={blocks.length}>{inlineContent(heading[1])}</h3>);
      index++;
      continue;
    }
    blocks.push(<p key={blocks.length}>{inlineContent(lines[index++])}</p>);
  }
  return blocks;
}
async function sendStream(
  id: string,
  message: string,
  documentId: string,
  onDelta: (text: string) => void,
): Promise<Detail> {
  const response = await fetch('/api/ai/conversations/' + id + '/messages/stream', {
    method: 'POST',
    credentials: 'same-origin',
    headers: { 'Content-Type': 'application/json', 'X-Eliza-Request': '1' },
    body: JSON.stringify({ message, ...(documentId ? { documentId } : {}) }),
  });
  if (!response.ok || !response.body) {
    const body = await response.json().catch(() => null);
    throw new Error(body?.message || t('Eliza AI could not complete the request. Try again.'));
  }
  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let buffer = '';
  let result: Detail | undefined;
  const consume = (frame: string) => {
    const event = frame.split('\n').find((line) => line.startsWith('event:'))?.slice(6).trim();
    const data = frame.split('\n').filter((line) => line.startsWith('data:')).map((line) => line.slice(5).trimStart()).join('\n');
    if (!event || !data) return;
    const value = JSON.parse(data);
    if (event === 'delta' && typeof value.text === 'string') onDelta(value.text);
    if (event === 'done') result = value as Detail;
    if (event === 'error') throw new Error(value.message || t('Eliza AI could not complete the request. Try again.'));
  };
  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    buffer = buffer.replace(/\r\n/g, '\n');
    let boundary: number;
    while ((boundary = buffer.indexOf('\n\n')) >= 0) {
      consume(buffer.slice(0, boundary));
      buffer = buffer.slice(boundary + 2);
    }
  }
  if (buffer.trim()) consume(buffer);
  if (!result) throw new Error(t('Eliza AI did not finish its answer. Try again.'));
  return result;
}
export function AiAgentPage() {
  useLanguage();
  const session = useSession();
  const canDocuments = session.data?.user.permissions.includes('purchases.read') ?? false;
  const canUpload = session.data?.user.permissions.includes('purchases.write') ?? false;
  const [id, setId] = useState(() => new URLSearchParams(window.location.search).get('id') || '');
  const [draft, setDraft] = useState('');
  const [file, setFile] = useState<File | null>(null);
  const [documentId, setDocumentId] = useState('');
  const [activeDocumentId, setActiveDocumentId] = useState(() => new URLSearchParams(window.location.search).get('document') || '');
  const [documentRecord, setDocumentRecord] = useState<DocumentRecord | null>(null);
  const [documentName, setDocumentName] = useState('');
  const [showDocuments, setShowDocuments] = useState(false);
  const [documentSearch, setDocumentSearch] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<unknown>(null);
  const [pending, setPending] = useState('');
  const [streamed, setStreamed] = useState('');
  const [localMessages, setLocalMessages] = useState<Message[] | null>(null);
  const [showHistory, setShowHistory] = useState(false);
  const fileInput = useRef<HTMLInputElement>(null);
  const end = useRef<HTMLDivElement>(null);
  const history = useQuery({
    queryKey: ['ai-conversations'],
    queryFn: () => api<Conversation[]>('/ai/conversations'),
  });
  const detail = useQuery({
    queryKey: ['ai-conversation', id],
    queryFn: () => api<Detail>('/ai/conversations/' + id),
    enabled: !!id,
  });
  const activeDocument = useQuery({
    queryKey: ['scanned-document', activeDocumentId],
    queryFn: () => api<DocumentRecord>('/documents/' + activeDocumentId),
    enabled: canDocuments && !!activeDocumentId,
  });
  const documents = useQuery({
    queryKey: ['scanned-documents', documentSearch],
    queryFn: () => api<Document[]>('/documents?search=' + encodeURIComponent(documentSearch)),
    enabled: canDocuments && showDocuments,
  });
  useEffect(() => {
    setLocalMessages(null);
  }, [id]);
  useEffect(() => {
    end.current?.scrollIntoView({ block: 'end', behavior: 'smooth' });
  }, [detail.data, localMessages, pending, streamed, busy]);
  const messages = localMessages ?? detail.data?.messages ?? [];
  const chosen = documents.data?.find((doc) => doc.id === documentId);
  const visibleDocument = documentRecord?.id === activeDocumentId ? documentRecord : activeDocument.data;
  function openDocument(next: string) {
    setActiveDocumentId(next);
    if (!next) { setDocumentId(''); setDocumentName(''); }
    setDocumentRecord(null);
    setShowDocuments(false);
    const search = new URLSearchParams(window.location.search);
    if (next) search.set('document', next); else search.delete('document');
    window.history.replaceState(null, '', '/ai' + (search.size ? '?' + search.toString() : ''));
  }
  function selectConversation(next: string) {
    setId(next);
    setDraft('');
    setFile(null);
    setDocumentId('');
    setDocumentName('');
    setError(null);
    setShowHistory(false);
    setShowDocuments(false);
    window.history.replaceState(null, '', next ? '/ai?id=' + next : '/ai');
    setActiveDocumentId('');
    setDocumentRecord(null);
  }
  function chooseFile(next?: File) {
    if (!next) return;
    if (!accepted.includes(next.type) || next.size > fileLimit) {
      setError(t('Choose a JPEG, PNG, WebP, or PDF file smaller than 8 MB.'));
      return;
    }
    setFile(next);
    setDocumentId('');
    setDocumentName('');
    setShowDocuments(false);
    setError(null);
  }
  async function upload(selected: File) {
    const dataUrl = await new Promise<string>((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = () => resolve(String(reader.result));
      reader.onerror = () => reject(new Error(t('The file could not be opened.')));
      reader.readAsDataURL(selected);
    });
    const result = await api<DocumentRecord>('/documents/scan', {
      filename: selected.name,
      dataUrl,
    });
    void queryClient.invalidateQueries({ queryKey: ['scanned-documents'] });
    queryClient.setQueryData(['scanned-document', result.id], result);
    openDocument(result.id);
    setDocumentRecord(result);
    return result.id;
  }
  async function send() {
    const text =
      draft.trim() || (file || documentId || activeDocumentId ? t('Please review this scanned document.') : '');
    if (!text || busy || (id && detail.isPending && !localMessages)) return;
    setBusy(true);
    setPending(text);
    setStreamed('');
    setError(null);
    let conversationId = id;
    try {
      if (!conversationId) {
        const created = await api<Conversation>('/ai/conversations', {});
        conversationId = created.id;
        setId(conversationId);
        window.history.replaceState(null, '', '/ai?id=' + conversationId + (activeDocumentId ? '&document=' + activeDocumentId : ''));
        void queryClient.invalidateQueries({ queryKey: ['ai-conversations'] });
      }
      let attached = documentId || activeDocumentId;
      if (file) {
        attached = await upload(file);
        setDocumentId(attached);
        setDocumentName(file.name);
        setFile(null);
      }
      const result = await sendStream(conversationId, text, attached, (chunk) =>
        setStreamed((current) => current + chunk),
      );
      setLocalMessages((current) => [
        ...(current ?? detail.data?.messages ?? []),
        ...result.messages,
      ]);
      setDraft('');
      setDocumentId('');
      setDocumentName('');
      void queryClient.invalidateQueries({ queryKey: ['ai-conversations'] });
      void queryClient.invalidateQueries({ queryKey: ['ai-conversation', conversationId] });
    } catch (cause) {
      setError(cause);
      setDraft(text);
    } finally {
      setPending('');
      setStreamed('');
      setBusy(false);
    }
  }
  return (
    <div className="ai-page">
      <aside className={'ai-history' + (showHistory ? ' is-open' : '')}>
        <div className="ai-history-heading">
          <strong>{t('Eliza AI')}</strong>
          <button
            type="button"
            aria-label={t('Close history')}
            onClick={() => setShowHistory(false)}
          >
            <X size={18} />
          </button>
        </div>
        <button type="button" className="ai-new" onClick={() => selectConversation('')}>
          <Plus size={17} />
          {t('New conversation')}
        </button>
        <div className="ai-history-list">
          <span className="ai-history-label">{t('Recent conversations')}</span>
          <ErrorMessage error={history.error} />
          {history.data?.map((item) => (
            <button
              type="button"
              className={id === item.id ? 'active' : ''}
              key={item.id}
              onClick={() => selectConversation(item.id)}
            >
              <Clock3 size={15} />
              <span>{item.title}</span>
            </button>
          ))}
          {history.data?.length === 0 && <p>{t('No conversations yet.')}</p>}
        </div>
      </aside>
      <main className="ai-main">
        <header className="ai-header">
          <button
            type="button"
            className="ai-history-toggle"
            onClick={() => setShowHistory((v) => !v)}
            aria-label={t('Conversation history')}
          >
            <Clock3 size={20} />
          </button>
          <span>
            <Sparkles size={18} />
            {t('Eliza AI')}
          </span>
          <button
            type="button"
            onClick={() => selectConversation('')}
            aria-label={t('New conversation')}
          >
            <Plus size={20} />
          </button>
        </header>
        <div className="ai-thread" role="log" aria-live="polite">
          {!id && !messages.length && (
            <div className="ai-welcome">
              <span className="ai-welcome-icon">
                <Sparkles size={30} />
              </span>
              <h1>{t('How can I help your store?')}</h1>
              <p>{t('Ask about sales, products, stock, purchases or scanned documents.')}</p>
            </div>
          )}
          <div className="ai-messages">
            <ErrorMessage error={detail.error} />
            {messages.map((message) => (
              <div className={'ai-message ai-message-' + message.role} key={message.id}>
                <div className="ai-message-label">
                  {message.role === 'assistant' ? t('Eliza AI') : t('You')}
                </div>
                <div className="ai-message-body">{messageContent(message.content)}</div>
                {message.document_id && (
                  <button type="button" className="ai-document-card" onClick={() => openDocument(message.document_id!)}>
                    <FileText size={19} />
                    <span>
                      {t('Open scanned document')}
                      <small>{t('AI-extracted document — review before using')}</small>
                    </span>
                  </button>
                )}
              </div>
            ))}
            {activeDocumentId && canDocuments && (
              <div className="ai-digital-document" id="digital-document">
                <div className="ai-digital-heading">
                  <strong>{t('Digital document')}</strong>
                  <button type="button" onClick={() => openDocument('')} aria-label={t('Close document')}><X size={18} /></button>
                </div>
                <p className="ai-document-note">{t('Save edits before asking Eliza about them.')}</p>
                <ErrorMessage error={activeDocument.error} />
                {activeDocument.isPending && !visibleDocument && <p>{t('Loading…')}</p>}
                {visibleDocument && <DocumentViewer record={visibleDocument} canEdit={canUpload} onSaved={(next) => {
                  setDocumentRecord(next);
                  queryClient.setQueryData(['scanned-document', next.id], next);
                  void queryClient.invalidateQueries({ queryKey: ['scanned-documents'] });
                }} />}
              </div>
            )}
            {pending && (
              <div className="ai-message ai-message-user ai-pending">
                <div className="ai-message-label">{t('You')}</div>
                <div className="ai-message-body">
                  <p>{pending}</p>
                </div>
              </div>
            )}
            {streamed && (
              <div className="ai-message ai-message-assistant ai-streaming">
                <div className="ai-message-label">{t('Eliza AI')}</div>
                <div className="ai-message-body">{messageContent(streamed)}</div>
              </div>
            )}
            {busy && !streamed && (
              <div className="ai-thinking" role="status">
                <span className="thinking-dots">
                  {file ? t('Reading your document…') : t('Thinking…')}
                </span>
              </div>
            )}
            <div ref={end} />
          </div>
        </div>
        <div className="ai-composer-wrap">
          <ErrorMessage error={error} />
          <div className="ai-composer">
            {(file || documentId || activeDocumentId) && (
              <div className="ai-attachment">
                <FileText size={17} />
                <span>
                  {file?.name || documentName || chosen?.filename || visibleDocument?.filename || t('Scanned document')}
                </span>
                <button
                  type="button"
                  aria-label={t('Remove attachment')}
                  onClick={() => {
                    setFile(null);
                    setDocumentId('');
                    setDocumentName('');
                    openDocument('');
                  }}
                >
                  <X size={15} />
                </button>
              </div>
            )}
            <textarea
              aria-label={t('Ask Eliza AI')}
              placeholder={t('Ask Eliza AI anything about your store…')}
              value={draft}
              onChange={(event) => setDraft(event.target.value)}
              onKeyDown={(event) => {
                if (event.key === 'Enter' && !event.shiftKey) {
                  event.preventDefault();
                  void send();
                }
              }}
              rows={2}
            />
            <div className="ai-composer-actions">
              <div className="ai-attach-actions">
                {canDocuments && (
                  <>
                    {canUpload && <input
                      ref={fileInput}
                      type="file"
                      accept={accepted.join(',')}
                      hidden
                      aria-label={t('Upload document')}
                      onChange={(event) => {
                        chooseFile(event.target.files?.[0]);
                        event.target.value = '';
                      }}
                    />}
                    {canUpload && <button
                      type="button"
                      className="ai-attach"
                      aria-label={t('Upload document')}
                      title={t('Upload document')}
                      onClick={() => fileInput.current?.click()}
                    >
                      <Paperclip size={20} />
                    </button>}
                    <button
                      type="button"
                      className="ai-existing"
                      onClick={() => setShowDocuments((v) => !v)}
                    >
                      {t('Digital documents')}
                    </button>
                  </>
                )}
              </div>
              <button
                type="button"
                className="ai-send"
                aria-label={t('Send')}
                disabled={busy || (!draft.trim() && !file && !documentId && !activeDocumentId)}
                onClick={() => void send()}
              >
                <ArrowUp size={19} />
              </button>
            </div>
            {showDocuments && (
              <div className="ai-document-picker">
                <input aria-label={t('Search digital documents')} placeholder={t('Search digital documents')} value={documentSearch} onChange={(event) => setDocumentSearch(event.target.value)} />
                <ErrorMessage error={documents.error} />
                {documents.isPending && <p>{t('Loading…')}</p>}
                {documents.data?.length === 0 && <p>{t('No scanned documents yet.')}</p>}
                {documents.data?.map((doc) => (
                  <button
                    type="button"
                    key={doc.id}
                    onClick={() => {
                      setDocumentId(doc.id);
                      setDocumentName(doc.filename);
                      setFile(null);
                      openDocument(doc.id);
                    }}
                  >
                    <FileText size={16} />
                    {doc.filename}
                  </button>
                ))}
              </div>
            )}
          </div>
          <p className="ai-note">
            {t('Eliza AI can make mistakes. Check important figures and scanned documents.')}
          </p>
        </div>
      </main>
    </div>
  );
}
